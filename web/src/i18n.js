export const IDIOMAS = ['es', 'en']

export function traductor(idioma) {
  const i = idioma === 'en' ? 1 : 0
  return (clave, vars) => {
    const par = T[clave]
    let s = par ? par[i] : clave
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v))
    return s
  }
}

export function idiomaInicial() {
  try {
    const q = new URLSearchParams(window.location.search).get('lang')
    if (q === 'es' || q === 'en') return q
    const guardado = localStorage.getItem('till-idioma')
    if (guardado === 'es' || guardado === 'en') return guardado
  } catch {
    // sin almacenamiento: se queda el idioma por omisión
  }
  return 'es'
}

export const Idioma = createContext({ idioma: 'es', t: traductor('es') })
export const useIdioma = () => useContext(Idioma)
